function yearGroupFromDob(dobStr) {
  const [d, m, y] = dobStr.split('/').map(Number);
  const today = new Date();
  const currentYear = today.getFullYear();
  const schoolYear = today.getMonth() >= 8 ? currentYear : currentYear - 1;
  const entryYear = Number(y) + (m >= 9 ? 5 : 4);
  return 'Year ' + (schoolYear - entryYear + 7);
}

